/**
 * 管家**第一次开口**说的那段话。
 *
 * 为什么非有不可：扫码成功之后，微信里其实什么都不会发生 —— 而一个不懂技术的人
 * 恰恰会把这理解成"没装好"。他就坐在那儿等，越等越觉得失败了。
 * （这不是猜的：同一个坏法在这个项目里已经出现过一次 —— 模型 key 贴错时
 * 什么都不报，只在几小时后表现为"管家不理你"，那是**最难自己查出来**的一种坏法。）
 *
 * 所以：**认下主人之后，管家先说一句**。这一句要办四件事，一句都不能少：
 *
 *   ① 报平安 —— "成了"，不是"没装好"。
 *   ② 给他**能直接抄的一句话**（人话，不是命令）—— 白纸一张的人需要的是例子。
 *   ③ 说清"要动你电脑的事我先问过你" —— 这是信任的地基。
 *   ④ 告诉他被问烦了怎么办（「以后这类都行」），以及哪儿能看到全部玩法。
 *
 * 写成一段纯文本、放在这里，是为了能用例把它钉住：**短到一屏看得完**。
 * 微信不是文档，太长的话没人会读第二遍。
 */
export function welcomeText(): string {
  return [
    '我是你的管家 —— 这台电脑现在归你遥控了。',
    '',
    '直接跟我说人话就行，比如：',
    '  · 桌面上都有什么？',
    '  · 帮我把下载里超过 100M 的文件挑出来',
    '  · 这台电脑还剩多少空间？',
    '',
    '要动你电脑的事（删东西、装东西、改配置），我一定**先问过你**才做，',
    '不会先做了再说。真被问烦了，回「以后这类都行 1」我就记住这一类、不再问。',
    '',
    '想看我都会哪几句：回「命令」',
    '想让我记住点事：回「记住 项目都在 code/ 里」',
    '万一我半天不理你：先回「自检」，我自己查一遍、告诉你哪儿不对；',
    '要是连这句也没人回，就再双击一次装我的那个文件（install.command）—— 我会重新起来，',
    '并把「哪儿不对」写在屏幕上',
  ].join('\n');
}

