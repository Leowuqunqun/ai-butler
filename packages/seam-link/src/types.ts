/**
 * `ctx.link` 的值类型 —— 跨机器链路上流动的东西。
 *
 * ⚠️ **这里不认识 agent、不认识消息、不认识文件。**
 * 链路是**传输**：它只负责把「一次方法调用」送过去、把过程和结果带回来。
 * 一旦让 `ctx.link` 认识 `AgentRequest`，那么以后每加一种能力（读文件、装软件、
 * 看屏幕）都要改这个 seam —— 而它们本质上都是同一种东西：**一次远程调用**。
 *
 * @module @butler/seam-link
 */

/**
 * 一台能被中枢管到的设备。
 *
 * 这是**中枢视角**的快照，不是节点的自我描述 —— 同一个节点，
 * 从局域网看得见、从 Tailscale 看不见时，`link` 字段就不一样。
 */
export interface DeviceInfo {
  /**
   * 稳定标识，例如 `'node-home'`。
   *
   * **不是主机名、不是 IP、不是随机数**：主机名会改、IP 会变、
   * 随机数每次重启都不同。它由节点第一次启动时生成并存在自己的
   * `state/` 里，之后一直不变 —— 用户的「以后都放那台电脑上」才能一直指对。
   */
  id: string;

  /** 人给的名字，例如「家里那台」。用户说的别名最终解析到 `id` */
  alias: string;

  /** `process.platform` 的值：`'darwin'` / `'linux'` / `'win32'` */
  os: string;

  /** 这台机器能干什么，例如 `['agent', 'files']`。中枢据此判断能不能派活 */
  capabilities: string[];

  /**
   * 最后一次听到它的时间（epoch ms）。**从没听到过就是 `null`**。
   *
   * 这个字段是用来**跟用户解释**的：那台电脑离线时不能说"连接失败"，
   * 要说"最后在线 3 小时前"。
   */
  lastSeen: number | null;

  /**
   * 现在**连得上**吗。
   *
   * ⚠️ 跟「看得见」是两件事，所以是两个字段：
   * 局域网里能听见它在广播（看得见），但它可能正在装东西、忙不过来（连不上）。
   * `discover()` 只保证前者，这一位得真的握一次手才算。
   */
  online: boolean;

  /** 从哪条链路看见的，例如 `'lan'` / `'tailscale'`。用于给用户解释"为什么连不上" */
  link: string;
}

/**
 * 一次请求过程中，节点回流给中枢的东西。
 *
 * 三种事件都带 `callId` —— 一条会话上可能同时跑着多个调用，
 * 不带这个字段，调用方就得自己猜哪个进度属于谁（猜错就是**串话**：
 * A 的进度显示在 B 的结果上）。
 */
export type LinkEvent =
  | {
      type: 'progress';
      /** 这次调用的标识，由 `request()` 生成，同一个调用内不变 */
      callId: string;
      /** 给用户看的一行进度。中枢会把它转述到微信里 */
      line: string;
    }
  | {
      type: 'done';
      callId: string;
      /** 方法自己的返回值，原样带回。**seam 不解释它** */
      result: unknown;
    }
  | {
      type: 'error';
      callId: string;
      /** 给人看的失败原因。别写 "ECONNRESET"，写"那台电脑上的进程被关掉了" */
      message: string;
      /** 机器可读的原因（可选），让中枢能按类型决定重试还是放弃 */
      code?: string;
    };

/**
 * 一次**配对**：把一台还不认识的新设备收进来。
 *
 * 为什么这是一个 seam 上的概念，而不是某个实现自己的私事：
 * 任何一条链路都躲不开同一件事 —— **用户怎么把第二台机器交给管家**。
 * 局域网那条要靠一次性配对码换密钥；尾巴网络那条其实不需要
 * （名册由 Tailscale 提供，密钥两边本来就一致）—— 所以这是**可选**的。
 */
export interface PairTarget {
  /** 那台电脑的地址。局域网里就是 IP，也可能是主机名 */
  host: string;
  /** 它听哪个端口。不写就用实现自己的默认 */
  port?: number;
  /**
   * 那台电脑屏幕上打出来的一次性配对码。
   *
   * ⚠️ **它可能经过微信**（用户是从另一台电脑的屏幕上抄过来的）。
   * 所以实现必须让它**只能成功一次、并且会作废** ——
   * 真正长期用的那把密钥不该走同一条路。
   */
  code: string;
}

/** `request()` 的可选项 */
export interface LinkRequestOpts {
  /**
   * 过程中的进度回调。
   *
   * **是每次请求独立的，不是会话级的。** 会话级回调看着更省事，
   * 但那样每个回调都得自己按 `callId` 过滤，漏一次就串话；
   * 挂在请求上，**串话在类型层面就不可能发生**。
   *
   * 不传就不报，不会因此被认为卡死。
   */
  onEvent?: (e: LinkEvent) => void;

  /**
   * 取消。**实现方应当尊重它** —— 远程跑一次任务可能几分钟，
   * 用户改主意了不该只能干等超时。
   */
  signal?: AbortSignal;
}

/**
 * 一次已建立的链路会话。
 *
 * 会话是可以并存多个的（同时问两台电脑），所以它是个**值**，不是服务位。
 */
export interface LinkSession {
  /** 这条会话通向哪台设备。跟 `DeviceInfo.id` 同源 */
  readonly deviceId: string;

  /**
   * 发一个请求，拿到应答。
   *
   * `method` 用点分名字（`'agent.run'` / `'fs.list'`），语义由**调用方和节点**约定，
   * seam 不参与 —— 链路不认识这些方法名，它只负责送到。
   */
  request(method: string, params: unknown, opts?: LinkRequestOpts): Promise<unknown>;

  /**
   * 会话脱落时回调（节点重启、网络断了、对面主动关了）。
   *
   * 返回一个取消订阅的函数。中枢靠它把「那台电脑现在离线」及时告诉用户，
   * 而不是等下一次请求超时才说。
   */
  onClose(handler: (reason?: string) => void): () => void;

  /** 关掉这条会话。必须能安全地重复调用 */
  close(): Promise<void>;
}

/**
 * 一条自检结果。`butler doctor` 会把它原样打给用户看。
 *
 * ⚠️ 写的时候想着"用户看不懂技术"：`detail` 说**现在是什么状态**，
 * `fix` 说**该干什么**。别写 "connection refused"，写"那台电脑没开着，或者不在同一个网络里"。
 *
 * > 这份定义在 `seam-channel`、`seam-agent` 里各有一份**一模一样的副本**，
 * > 这里是第三份。**是故意的**：每个 seam 包都要能单独装、单独用，
 * > 不想让「装个链路」顺带把微信通道的依赖拖进来。
 * > 类型是结构化的，三份形状相同 ⇒ 互相赋值合法，doctor 照样能统一处理。
 * > **但第四份出现时就该抽 `@butler/seam-kit` 了** —— 三份是忍耐，四份是债。
 */
export interface HealthCheck {
  /** 检查项的名字，会打在最前面，例如 `'和家里那台的链路'` */
  name: string;
  /** 过了没有 */
  ok: boolean;
  /** 现在是什么状态。**过了也要写** */
  detail?: string;
  /** 没过的话该怎么办。这一句决定用户能不能自己解决 */
  fix?: string;
}
