/**
 * 通道能力的**数据形状**。这些类型是通道实现与核心层之间的契约，
 * 改动等于破坏兼容，要慎重。
 *
 * 设计上的两条底线：
 *
 * 1. **附件永远是"本机路径"，不是 URL、也不是 Buffer。**
 *    通道自己负责把远端的东西取回本地（微信要下载+解密，Telegram 要给 token），
 *    核心层只看见一个能直接读的文件。这样核心层不需要知道任何通道的下载细节。
 *
 * 2. **`raw` 是逃生舱，核心层不许读。**
 *    通道私有的原始事件挂在 `raw` 上，给调试和通道自己的高级用法留个口子；
 *    一旦核心层开始读 `raw`，这个 seam 就白拆了。
 */

/** 附件的种类。`unknown` 是兜底，不代表通道支持 */
export type FileKind = 'image' | 'video' | 'file' | 'voice' | 'unknown';

/**
 * 一个**已经落到本机**的附件。
 *
 * 通道必须保证：拿到这个对象时，`path` 已经是一个可读的真实文件。
 * 不允许"按需再下载"——那会把通道的复杂度漏给核心层。
 */
export interface LocalFile {
  /** 本机绝对路径 */
  path: string;
  /** 文件名（已做安全处理，可直接展示） */
  name: string;
  /** MIME，猜不出时用 application/octet-stream */
  mime: string;
  /** 字节数 */
  size: number;
  kind: FileKind;
}

/**
 * 一条入站消息：通道 → 核心。
 *
 * 语音**不需要**单独的类型：通道自己转写成文本塞进 `text` 即可
 * （微信服务端已经转好了）。所以核心层永远只需要处理"文本 + 附件"。
 */
export interface InboundMessage {
  /** 通道标识，例如 `wechat` */
  channel: string;
  /** 通道内的发送者标识（微信是 userId，Telegram 是 chat id） */
  fromId: string;
  /** 文本，或语音转写结果。纯附件消息时为 undefined */
  text?: string;
  /**
   * 用户说这句话时**引用**的那条消息（压成一行纯文本；引用的是媒体就说清楚是什么）。
   *
   * 为什么是独立字段，而不是并进 `text` 的一行前缀：
   *
   *   · **路由不能看它。** 路由只认"某一行以 `@` 开头"，如果引用的那句话里
   *     恰好有 `@某台设备`，并进正文会让这条消息被送到那台设备上去执行 ——
   *     用户只是在引用自己以前说过的话，不是在叫设备。
   *   · **agent 要看它。** 连着发好几条时，"他在回哪句"是理解问题的前提
   *     （内核把它作为上下文放进提示词）。
   *   · 每个通道的引用形状都不一样（微信是 `ref_msg`，Telegram 是 `reply_to_message`），
   *     通道负责压成纯文本，内核只认这一个字段。
   */
  quote?: string;
  /** 已下载到本机的附件（见 LocalFile 的约定） */
  files?: LocalFile[];
  /**
   * 回复这条消息时要带上的凭据。
   * 微信必须有（否则不知道回哪个会话），别的通道可能用不上。
   */
  contextToken?: string;
  /** 通道私有的原始事件。**核心层不要读** */
  raw?: unknown;
}

/** 发送时的可选参数 */
export interface SendOpts {
  /** 回复哪个会话（一般直接透传 InboundMessage.contextToken） */
  contextToken?: string;
  /**
   * 这条消息**在回哪一句**（传原文，不是"要显示成什么样"）。
   *
   * 怎么显示是通道自己的事 —— 这正是这个字段存在的理由：
   *
   *   · 微信协议**没有引用回复字段** → 只能把原话截一段顶在文本前面（`↩ …`）；
   *   · Telegram **有原生的引用回复** → 拿 `contextToken` 里那个消息号走 reply，
   *     文本一个字都不用动。
   *
   * 换句话说：内核只说"我在回这句"，**不替通道决定它长什么样**。
   * 以前这件事写在内核里，结果是 Telegram 用户会看到同一句话被引用两次
   * （原生引用一次、文本前缀又一次）。
   *
   * 规则一句话：**终结性回复传，过程性消息不传。**
   *
   *   · 终结性 = 这条消息的事就此了结（答复、出错、拒收、命令结果、附件与配文）；
   *   · 过程性 = 还在路上（进度播报、队列回执）—— 这类**不传**，
   *     否则用户每收到一条"还在处理…"都被引用一次，看着很吵。
   *
   * `sendFile` 也认它（Telegram 把文件挂成原生引用回复）。微信的发文件**没有**
   * 引用能力（协议里连消息 id 都没有）—— 那边如实忽略，不假装支持。
   */
  quote?: string;
  /**
   * 单条文本的字符上限，超出由通道自行分条。
   *
   * ⚠️ **只有 `sendText` 认这个字段。**
   */
  maxChars?: number;
  /**
   * 发附件时的配文。
   *
   * ⚠️ 今天只有 Telegram 的 `sendFile` 认它（微信的协议里配文是单独一条消息，
   * 所以内核是自己先 `sendText` 再发文件）。**内核目前不传这个字段。**
   */
  caption?: string;
}

/** 发送结果。通道如实报告，核心层用来记流水 */
export interface SendResult {
  /** 文本被切成了几段 */
  chunks?: number;
  /** 实际发出的文件名 */
  fileName?: string;
  /** 实际发出的字节数 */
  size?: number;
}

/**
 * 一条自检结果。`butler doctor` 会把它原样打给用户看。
 *
 * ⚠️ 写的时候想着"用户看不懂技术"：`detail` 说**现在是什么状态**，
 * `fix` 说**该干什么**。别写 "token expired" 这种话，
 * 写"微信登录过期了，重新扫一下码"。
 */
export interface HealthCheck {
  /** 检查项的名字，会打在最前面，例如 `'微信登录态'` */
  name: string;
  /** 过了没有 */
  ok: boolean;
  /** 现在是什么状态。**过了也要写** —— "已登录"比一个光秃秃的勾有用得多 */
  detail?: string;
  /** 没过的话该怎么办。这一句决定用户能不能自己解决 */
  fix?: string;
}
